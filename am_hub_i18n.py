def normalize_language(value: str) -> str:
    value = str(value or "es").strip().lower()
    return "en" if value in {"en", "english", "inglés", "ingles"} else "es"


def translate(text: str, language: str = "es") -> str:
    """O(1), local-only lookup. Unknown/user-generated text is preserved."""
    text = str(text)
    return EN.get(text, text) if normalize_language(language) == "en" else text
